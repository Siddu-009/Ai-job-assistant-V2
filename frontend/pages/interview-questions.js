import { useState } from "react";

export default function InterviewQuestions() {

  const [role, setRole] = useState("");
  const [topic, setTopic] = useState("");
  const [difficulty, setDifficulty] = useState("Intermediate");
  const [questions, setQuestions] = useState([]);
  const [loading, setLoading] = useState(false);

  const generateQuestions = async () => {

    if (!role) {

      alert("Please enter a job role.");

      return;

    }

    setLoading(true);

    try {

      const response = await fetch(

        "/api/interview-questions/",

        {

          method: "POST",

          headers: {

            "Content-Type": "application/json"

          },

          body: JSON.stringify({

            role,

            topic,

            difficulty

          })

        }

      );

      const data = await response.json();

      setQuestions(

        data.questions ||

        data ||

        []

      );

    }

    catch {

      alert("Unable to generate interview questions.");

    }

    setLoading(false);

  };

  const copyQuestions = () => {

    navigator.clipboard.writeText(

      questions.join("\n\n")

    );

    alert("Copied Successfully");

  };

  return (

<div

style={{

maxWidth:"1200px",

margin:"40px auto",

background:"#fff",

padding:"35px",

borderRadius:"20px",

boxShadow:"0 15px 35px rgba(0,0,0,.08)"

}}

>

<h1>

AI Interview Questions

</h1>

<p

style={{

color:"#6b7280"

}}

>

Practice interview questions generated by AI.

</p>

<input

placeholder="Job Role"

value={role}

onChange={(e)=>setRole(e.target.value)}

style={input}

/>

<input

placeholder="Topic (AWS, Docker, Kubernetes...)"

value={topic}

onChange={(e)=>setTopic(e.target.value)}

style={input}

/>

<select

value={difficulty}

onChange={(e)=>setDifficulty(e.target.value)}

style={input}

>

<option>Beginner</option>

<option>Intermediate</option>

<option>Advanced</option>

</select>

<button

onClick={generateQuestions}

disabled={loading}

style={button}

>

{

loading

?

"Generating..."

:

"Generate Questions"

}

</button>

{

questions.length>0 &&

<>

<button

onClick={copyQuestions}

style={greenButton}

>

Copy Questions

</button>

<div

style={{

marginTop:"30px"

}}

>

{

questions.map((question,index)=>(

<div

key={index}

style={{

padding:"20px",

marginBottom:"20px",

background:"#f8fafc",

borderRadius:"12px",

border:"1px solid #e5e7eb"

}}

>

<h3>

Question {index+1}

</h3>

<p>

{question}

</p>

</div>

))

}

</div>

</>

}

</div>

);

}

const input={

width:"100%",

padding:"14px",

marginTop:"20px",

borderRadius:"10px",

border:"1px solid #d1d5db"

};

const button={

width:"100%",

padding:"15px",

marginTop:"20px",

background:"#2563eb",

color:"#fff",

border:"none",

borderRadius:"10px",

cursor:"pointer",

fontSize:"16px"

};

const greenButton={

width:"100%",

padding:"15px",

marginTop:"20px",

background:"#16a34a",

color:"#fff",

border:"none",

borderRadius:"10px",

cursor:"pointer",

fontSize:"16px"

};
